import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Department, Employee, Payslip, WorkspaceSettings } from '@/lib/types/hr';

export interface GeneratePayslipPDFParams {
  payslip: Payslip;
  employee: Employee;
  department?: Department;
  settings: WorkspaceSettings;
}

/**
 * Generates an A4 Payslip PDF document entirely on the client using jsPDF.
 * Returns the jsPDF instance so callers can either `.save()` or inspect in unit tests.
 */
export function createPayslipPdfDocument({
  payslip,
  employee,
  department,
  settings,
}: GeneratePayslipPDFParams): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const cur = settings.currencySymbol || '$';
  const fmt = (n: number) => `${cur}${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

  // Header Banner
  doc.setFillColor(13, 148, 136); // #0D9488 Teal Accent
  doc.rect(0, 0, 210, 34, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text(settings.logoText || 'PEOPLIX HR', 16, 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(settings.companyName || 'Peoplix Technologies Inc.', 16, 23);
  doc.text('SIMULATED PAYSLIP STATEMENT — DEMO PORTFOLIO RECORD', 16, 29);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text(`PAY PERIOD: ${payslip.periodLabel.toUpperCase()}`, 194, 16, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`Payslip ID: ${payslip.id}`, 194, 23, { align: 'right' });
  doc.text(`Issued Date: ${payslip.issuedDate}`, 194, 29, { align: 'right' });

  // Employee Metadata Box
  doc.setTextColor(23, 32, 51);
  doc.setDrawColor(231, 234, 240);
  doc.setFillColor(249, 250, 252);
  doc.roundedRect(16, 42, 178, 32, 2, 2, 'FD');

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('EMPLOYEE NAME', 22, 50);
  doc.text('EMPLOYEE ID', 110, 50);
  doc.text('JOB TITLE', 22, 62);
  doc.text('DEPARTMENT', 110, 62);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(23, 32, 51);
  doc.text(employee.fullName, 22, 55);
  doc.text(employee.employeeCode, 110, 55);
  doc.text(employee.jobTitle, 22, 67);
  doc.text(department?.name || 'General Operations', 110, 67);

  // Earnings & Deductions Table
  autoTable(doc, {
    startY: 82,
    margin: { left: 16, right: 16 },
    head: [['Earnings Component', 'Amount', 'Deductions Component', 'Amount']],
    body: [
      [
        'Base Salary',
        fmt(payslip.earningsBreakdown.baseSalary),
        'Standard Benefit & Tax Simulation',
        fmt(payslip.deductionsBreakdown.configuredDeduction),
      ],
      [
        'Housing Allowance',
        fmt(payslip.earningsBreakdown.housingAllowance),
        'Unpaid Leave Adjustment',
        fmt(payslip.deductionsBreakdown.unpaidLeaveAdjustment),
      ],
      [
        'Transport Allowance',
        fmt(payslip.earningsBreakdown.transportAllowance),
        '',
        '',
      ],
      [
        'Meal & Wellness Allowance',
        fmt(payslip.earningsBreakdown.mealAllowance),
        '',
        '',
      ],
      [
        'Performance & Spot Bonus',
        fmt(payslip.earningsBreakdown.bonus),
        '',
        '',
      ],
      [
        { content: 'Total Gross Earnings', styles: { fontStyle: 'bold' } },
        { content: fmt(payslip.grossPay), styles: { fontStyle: 'bold' } },
        { content: 'Total Deductions', styles: { fontStyle: 'bold' } },
        { content: fmt(payslip.totalDeductions), styles: { fontStyle: 'bold' } },
      ],
    ],
    theme: 'grid',
    headStyles: {
      fillColor: [23, 32, 51],
      textColor: [255, 255, 255],
      fontSize: 9.5,
    },
    bodyStyles: {
      fontSize: 9.5,
      textColor: [23, 32, 51],
    },
  });

  const finalY = (doc as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? 150;

  // Net Pay Summary Banner
  doc.setFillColor(232, 247, 244); // Soft teal #E8F7F4
  doc.setDrawColor(13, 148, 136);
  doc.roundedRect(16, finalY + 10, 178, 22, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 118, 110);
  doc.text('NET PAYABLE SIMULATION AMOUNT', 22, finalY + 23);

  doc.setFontSize(15);
  doc.setTextColor(23, 32, 51);
  doc.text(fmt(payslip.netPay), 188, finalY + 23.5, { align: 'right' });

  // Portfolio Disclaimer Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text(
    'DISCLAIMER: This document is generated by PEOPLIX HR for interactive portfolio demonstration purposes only.',
    16,
    finalY + 44
  );
  doc.text(
    'It does not represent real compensation, statutory tax withholding, banking disbursement, or legal payroll certification.',
    16,
    finalY + 49
  );

  return doc;
}

export function downloadPayslipPdf(params: GeneratePayslipPDFParams): void {
  const doc = createPayslipPdfDocument(params);
  const cleanName = params.employee.fullName.toLowerCase().replace(/\s+/g, '-');
  doc.save(`peoplix-payslip-${params.payslip.periodMonth}-${cleanName}.pdf`);
}
